"""Export the live API contract, risk schema, and matching TypeScript types."""
import json
import tempfile
from pathlib import Path

from .api import create_app
from .models import RiskSummary


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(v) for v in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + ts(schema["items"]) + ">"
    if kind == "object" or "properties" in schema:
        if not schema.get("properties"):
            additional = schema.get("additionalProperties", {})
            return "Record<string, " + (ts(additional) if isinstance(additional, dict) else "unknown") + ">"
        required = schema.get("required", [])
        lines = ["{"]
        for key, value in schema["properties"].items():
            lines.append("  " + json.dumps(key) + ("" if key in required else "?") + ": " + ts(value) + ";")
        return "\n".join(lines + ["}"])
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def main():
    root = Path(__file__).parent
    with tempfile.TemporaryDirectory() as directory:
        spec = create_app(Path(directory) / "export.db").openapi()
    (root / "openapi.json").write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    contract = root / "contracts"
    contract.mkdir(exist_ok=True)
    risk = {"$schema": "https://json-schema.org/draft/2020-12/schema", **RiskSummary.model_json_schema()}
    (contract / "risk-summary.schema.json").write_text(json.dumps(risk, indent=2) + "\n", encoding="utf-8")
    types = "// Generated by python -m Project.chatbot_app.export_contract. Do not edit.\n\n"
    for name, schema in spec["components"]["schemas"].items():
        types += f"export type {name} = {ts(schema)};\n\n"
    (contract / "types.ts").write_text(types, encoding="utf-8")
    print("Exported OpenAPI, risk-summary schema, and TypeScript models.")


if __name__ == "__main__":
    main()
